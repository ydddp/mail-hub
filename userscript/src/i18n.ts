export const DICTIONARIES: Record<Lang, Record<MessageKey, string>> = { zh, en };

let current: Lang = 'zh';

/** Chinese for any zh-* browser language, English for everything else. */
export function resolveLang(preference: LangPreference, browserLanguages: readonly string[]): Lang {
  if (preference !== 'auto') return preference;
  const first = browserLanguages.find((language) => language.trim() !== '') ?? '';
  return first.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function setLang(lang: Lang): void {
  current = lang;
}

export function currentLang(): Lang {
  return current;
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = DICTIONARIES[current][key] ?? DICTIONARIES.zh[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
